"""
Text Parsing Utilities for Raw Mode Agents.

This module handles the extraction of structured data (metrics, plans, code)
from natural language Markdown outputs generated by the agents.
"""

import re
from typing import Any
from ..logging import get_logger

logger = get_logger()


# =============================================================================
# CODER PARSING
# =============================================================================

def parse_coder_output(text: str) -> Any:
    """
    Extracts python code from text. 
    Handles:
    - Raw code
    - ```python ... ``` blocks
    - ``` ... ``` blocks
    """
    code = text.strip()
    
    # Check for markdown blocks and extract if present
    match = re.search(r'```(?:python)?\s*(.*?)\s*```', text, re.DOTALL | re.IGNORECASE)
    if match:
        code = match.group(1).strip()
        
    return code
