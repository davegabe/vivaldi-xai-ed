    calculations: List[CalculationResult] = field(default_factory=list)
    generated_images: List[str] = field(default_factory=list) # Absolute paths to generated PNGs
    image_reviews: List[Any] = field(default_factory=list) # All clinical reviews of images
    
    verified: bool = False
    processing_time_ms: float = 0.0
    iterations_used: int = 1
    phase_durations: Dict[str, float] = field(default_factory=dict)
