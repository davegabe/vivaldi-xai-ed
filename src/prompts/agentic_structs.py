@dataclass
class CalculationResult:
    """Result of a code execution."""
    success: bool
    metric_name: str
    value: Any
    unit: str = ""
    interpretation: str = ""
    code_executed: str = ""
    error_message: str = ""
    image_paths: List[str] = field(default_factory=list)  # Multiple images supported
    script_path: Optional[str] = None  # Path to the script that generated the result

    def to_summary(self) -> str:
        """Return a clinical summary without the raw code."""
        if not self.success:
            return f"- {self.metric_name}: {self.error_message}"
        
        summary = f"- {self.metric_name}: {self.value} {self.unit} ({self.interpretation})"
        return summary


@dataclass
class IterationHistory:
    """Track iteration state for the pipeline."""
    feedbacks: List[str] = field(default_factory=list)
    image_reviews: List[Any] = field(default_factory=list)  # List of ImageReview objects
    visualization_summaries: Dict[str, str] = field(default_factory=dict)  # {metric_name: description} for Planner feedback
    retry_metrics: List[str] = field(default_factory=list)
    
    @property
    def last_feedback(self) -> Optional[str]:
        return self.feedbacks[-1] if self.feedbacks else None
    
    def add_feedback(self, feedback: str) -> None:
        if feedback:
            self.feedbacks.append(feedback)


@dataclass
class AgentOutput:
    """Complete output from the agentic pipeline."""
    visit_id: str
    # New Architecture Fields
    doctor_history: List[str] = field(default_factory=list)
    consultant_history: List[str] = field(default_factory=list)
    
    # Shared Fields
