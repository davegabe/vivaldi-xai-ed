VitalName = Literal["hr", "sbp", "dbp", "rr", "spo2", "temp"]

class ThresholdRange(PydanticBaseModel):
    """Structured range for vital sign thresholds."""
    low: float = Field(
        description="Lower bound of the range."
    )
    high: float = Field(
        description="Upper bound of the range."
    )

class TriageVitalThresholds(PydanticBaseModel):
    """Thresholds for each vital sign."""
    hr: Optional[ThresholdRange] = Field(None, description="Heart Rate thresholds")
    sbp: Optional[ThresholdRange] = Field(None, description="Systolic BP thresholds")
    dbp: Optional[ThresholdRange] = Field(None, description="Diastolic BP thresholds")
    rr: Optional[ThresholdRange] = Field(None, description="Respiratory Rate thresholds")
    spo2: Optional[ThresholdRange] = Field(None, description="SpO2 thresholds")
    temp: Optional[ThresholdRange] = Field(None, description="Temperature thresholds")

    @model_validator(mode='before')
    @classmethod
    def normalize_keys(cls, data: Any) -> Any:
        if not isinstance(data, dict):
            return data
            
        VITAL_MAPPING = {
            "hr": ["heart rate", "heartrate", "hr", "bpm", "heart_rate"],
            "sbp": ["systolic bp", "systolicbp", "sbp", "systolic", "systolic_bp"],
            "dbp": ["diastolic bp", "diastolicbp", "dbp", "diastolic", "diastolic_bp"],
            "rr": ["respiratory rate", "respiratoryrate", "rr", "resprate", "respiratory_rate"],
            "spo2": ["spo2", "o2 sat", "o2sat", "oxygen saturation", "pulse ox", "o2_sat", "oxygen_saturation", "pulse_ox"],
            "temp": ["temperature", "temp", "t", "temperature_c", "temperature_f", "temp_c", "temp_f", "temperature_celsius", "temperature_fahrenheit", "temp_celsius", "temp_fahrenheit"]
        }
        
        # Flatten mapping for reverse lookup
        REVERSE_MAPPING = {}
        for canonical, aliases in VITAL_MAPPING.items():
            for alias in aliases:
                REVERSE_MAPPING[alias.lower()] = canonical

        new_dict = {}
        for k, v in data.items():
            norm_k = REVERSE_MAPPING.get(k.lower(), k)
            new_dict[norm_k] = v
        return new_dict

